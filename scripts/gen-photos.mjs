const seen = new Map();
for (const [key, idx] of Object.entries(MAP)) {
  if (idx == null || !ids[idx]) throw new Error(`Bad index for ${key}: ${idx}`);
  if (seen.has(idx)) throw new Error(`Index ${idx} used by both ${seen.get(idx)} and ${key}`);
  seen.set(idx, key);
}

const entries = Object.entries(MAP)
  .map(([key, idx]) => `  ${key}: "${ids[idx]}",`)
  .join("\n");

const out = `// AUTO-GENERATED by scripts/gen-photos.mjs — do not edit by hand.
// Each value is an Unsplash photo id, verified to resolve.

export const PHOTOS = {
${entries}
} as const;

export type PhotoKey = keyof typeof PHOTOS;

/** Builds a sized, cropped Unsplash URL for a photo key. */
export function photoUrl(
  key: PhotoKey,
  { w = 800, h, q = 72 }: { w?: number; h?: number; q?: number } = {}
): string {
  const params = new URLSearchParams({
    auto: "format",
    fit: "crop",
    q: String(q),
    w: String(w),
  });
  if (h) params.set("h", String(h));
  return \`https://images.unsplash.com/photo-\${PHOTOS[key]}?\${params.toString()}\`;
}
`;

